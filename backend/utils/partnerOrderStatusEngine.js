export const normalizePartnerStatusInput = (status) => {
  if (!status || typeof status !== "string") {
    return null
  }

  const key = status.trim().toUpperCase().replace(/\s+/g, "_")

  return PARTNER_TO_INTERNAL_STATUS[key] || PARTNER_ORDER_STATUS[key] || null
}

export const toInternalPartnerOrderStatus = (status) =>
  normalizePartnerStatusInput(status)

export const toPartnerOrderStatus = (internalStatus) =>
  INTERNAL_TO_PARTNER_STATUS[internalStatus] || internalStatus

export const isValidPartnerOrderStatusTransition = (fromStatus, toStatus) => {
  const allowedNext = PARTNER_ALLOWED_TRANSITIONS[fromStatus] || []
  return allowedNext.includes(toStatus)
}

export const getPartnerAllowedNextStatuses = (status) =>
  PARTNER_ALLOWED_TRANSITIONS[status] || []

export const PARTNER_FILTER_STATUSES = Object.freeze(
  Object.keys(PARTNER_TO_INTERNAL_STATUS)
)